# PlatformIO pre-build script: gzips data/portal.html into include/page_gz.h.
# Deterministic (gzip timestamp 0), rewrites the header only when it changed, and checks the page's script
# with `node --check` when Node.js is available (a script that does not parse kills the whole page).
import gzip
import hashlib
import os
import re
import shutil
import subprocess
import tempfile

Import("env")  # noqa: F821  (provided by PlatformIO)

root = env["PROJECT_DIR"]  # noqa: F821
src = os.path.join(root, "data", "portal.html")
dst = os.path.join(root, "include", "page_gz.h")

html = open(src, "rb").read()

node = shutil.which("node")
m = re.search(rb"<script>(.*)</script>", html, re.S)
if node and m:
    with tempfile.NamedTemporaryFile("wb", suffix=".js", delete=False) as f:
        f.write(m.group(1))
        js = f.name
    r = subprocess.run([node, "--check", js], capture_output=True, text=True)
    os.unlink(js)
    if r.returncode:
        raise SystemExit("portal script will not parse:\n" + r.stderr)
elif not node:
    print("[WARN] node not found - the portal's script was NOT syntax-checked")

gz = gzip.compress(html, compresslevel=9, mtime=0)
etag = hashlib.sha256(gz).hexdigest()[:16]
lines = ["// Generated by scripts/page.py from data/portal.html. Do not edit.", "#pragma once", "#include <pgmspace.h>",
         f'#define PAGE_ETAG "{etag}"', f"#define PAGE_GZ_LEN {len(gz)}", "static const uint8_t PAGE_GZ[] PROGMEM = {"]
for i in range(0, len(gz), 20):
    lines.append("  " + ",".join(str(b) for b in gz[i:i + 20]) + ",")
lines.append("};")
text = "\n".join(lines) + "\n"
old = open(dst).read() if os.path.exists(dst) else ""
if text != old:
    open(dst, "w", newline="\n").write(text)
    print(f"page_gz.h: {len(html)} bytes -> {len(gz)} gzipped, etag {etag}")
