# PlatformIO pre-build script: writes include/version.h (not committed) with the firmware version
#   v.MAJOR.MINOR.YYYYMMDDTHHMMSSZ
# (MAJOR.MINOR from the file VERSION; the last part is the committer time of the commit it was built from, in
# UTC, so every build of one commit carries the same version; "-modified" when `git status --porcelain` lists
# anything; the "v." in front is part of the format). Also the commit's short sha.
# Building from a copy without .git: set FW_REPO to the firmware folder in the repository.
import datetime
import os
import re
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO)

root = env["PROJECT_DIR"]  # noqa: F821
repo = os.environ.get("FW_REPO") or root


def git(*args):
    try:
        r = subprocess.run(["git", "-c", "safe.directory=*"] + list(args), cwd=repo, capture_output=True, text=True,
                           timeout=10)
        return r.stdout.strip() if r.returncode == 0 else None
    except Exception:
        return None


major_minor = open(os.path.join(repo, "VERSION")).read().strip()
if not re.fullmatch(r"\d+\.\d+", major_minor):
    raise SystemExit("VERSION must hold MAJOR.MINOR, for example 0.3")
sha = re.sub(r"[^0-9a-f]", "", git("rev-parse", "--short=7", "HEAD") or "")[:12] or "unknown"
ct = git("show", "-s", "--format=%ct", "HEAD") or ""
stamp = datetime.datetime.fromtimestamp(int(ct), datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ") if ct.isdigit() \
    else "00000000T000000Z"
status = git("status", "--porcelain")
modified = status is None or status != "" or sha == "unknown"         # a failed status counts as modified
version = "v.%s.%s%s" % (major_minor, stamp, "-modified" if modified else "")
short = "v.%s %s" % (major_minor, stamp[2:13] + "Z")          # for the screen: v.0.3 261102T2332Z
if modified:
    short += "*"
text = ("// Generated by scripts/version.py on every build. Do not edit; not committed.\n"
        "#pragma once\n"
        '#define FW_VERSION "%s"\n'
        '#define FW_VERSION_SHORT "%s"\n'
        '#define FW_COMMIT "%s"\n') % (version, short, sha)
open(os.path.join(root, "include", "version.h"), "w", newline="\n").write(text)
print("version:", version, "commit", sha)
